export function glyph(ch: string): string[] | undefined {
  return G[ch];
}
/** 한 글자를 찍고 폭을 돌려준다. 숫자 · '-' 은 9줄 칸의 가운데에 */
export function drawGlyph(p: Pix, ch: string, x: number, y: number, c: Color): number {
  const g = glyph(ch);
  if (!g) return ch === ' ' ? 4 : 0;
  const dy = g.length < 9 ? 1 : 0;
  g.forEach((r, yy) => {
    for (let xx = 0; xx < r.length; xx++) if (r[xx] === '#') p.set(x + xx, y + yy + dy, c);
  });
  return g[0].length;
}
/** 가로 글씨 */
export function textH(p: Pix, s: string, x: number, y: number, c: Color, gap = 1): number {
  let cx = x;
  for (const ch of s) cx += drawGlyph(p, ch, cx, y, c) + gap;
  return cx - x - gap;
}
export function textWidth(s: string, gap = 1): number {
  let w = 0;
  for (const ch of s) w += (ch === ' ' ? 4 : (glyph(ch)?.[0].length ?? 0)) + gap;
  return Math.max(0, w - gap);
}
/** 세로 글씨 (책등): 글자를 위에서 아래로, 가운데 맞춤 */
export function textV(p: Pix, s: string, cx: number, y: number, c: Color): number {
  let cy = y;
  for (const ch of s) {
    if (ch === ' ') {
      cy += 4;
      continue;
    }
    const g = glyph(ch);
    if (!g) continue;
    drawGlyph(p, ch, cx - Math.floor(g[0].length / 2), cy, c);
    cy += (g.length < 9 ? 8 : 10);
  }
  return cy - y;
}
export function textVHeight(s: string): number {
  let h = 0;
  for (const ch of s) h += ch === ' ' ? 4 : glyph(ch) ? (glyph(ch)!.length < 9 ? 8 : 10) : 0;
  return h;
}
export function tiny(p: Pix, s: string, x: number, y: number, c: Color): number {
  let cx = x;
  for (const ch of s) {
    const g = D3[ch];
    if (!g) {
      cx += 2;
      continue;
    }
    g.forEach((r, yy) => {
      for (let xx = 0; xx < 3; xx++) if (r[xx] === '#') p.set(cx + xx, y + yy, c);
    });
    cx += 4;
  }
  return cx - x - 1;
}

